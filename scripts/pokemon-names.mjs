// Every Pokémon species name, for the collection's "Did you mean" (#266): a search for a real Pokémon that isn't in
// the collection (Lugia, Baltoy) must not be "corrected" to a word that is (Luxio, Bolt). It says the card isn't
// here yet and offers the suggestion form instead.
//
//   node scripts/pokemon-names.mjs    rewrite docs/pokemon-names.js from PokeAPI's English species names
//
// Run it when new Pokémon are released. The source is PokeAPI's data on GitHub (pokemon_species_names.csv,
// language 9 = English); app.js only needs the normalized words, so that's what the file holds.
import { writeFile } from "node:fs/promises";

const SOURCE = "https://raw.githubusercontent.com/PokeAPI/pokeapi/master/data/v2/csv/pokemon_species_names.csv";
const OUT = "docs/pokemon-names.js";

// The same normalization as normalizeSearchText in app.js, then letters and digits only.
const normalize = (value) => String(value).normalize("NFD").replace(/[̀-ͯ]/g, "").toLowerCase();

function parseCsvLine(line) {
  const cells = [];
  let cell = "";
  let quoted = false;
  for (let index = 0; index < line.length; index += 1) {
    const char = line[index];
    if (quoted) {
      if (char === '"' && line[index + 1] === '"') { cell += '"'; index += 1; } else if (char === '"') quoted = false;
      else cell += char;
    } else if (char === '"') quoted = true;
    else if (char === ",") { cells.push(cell); cell = ""; } else cell += char;
  }
  cells.push(cell);
  return cells;
}

const response = await fetch(SOURCE, { signal: AbortSignal.timeout(30_000) });
if (!response.ok) throw new Error(`${SOURCE} returned ${response.status}`);
const [header, ...rows] = (await response.text()).trim().split(/\r?\n/);
const columns = parseCsvLine(header);
const language = columns.indexOf("local_language_id");
const nameColumn = columns.indexOf("name");
const names = rows.map(parseCsvLine).filter((cells) => cells[language] === "9").map((cells) => cells[nameColumn]);
if (names.length < 1000) throw new Error(`Only ${names.length} English names: the source looks wrong, so nothing was written`);

// Each name's words ("mr", "mime") and the whole name run together ("mrmime", "hooh", "farfetchd"), 3+ letters.
const words = new Set();
for (const name of names) {
  const parts = normalize(name).split(/[^a-z0-9]+/).filter(Boolean);
  for (const word of [...parts, parts.join("")]) if (word.length >= 3) words.add(word);
}

const file = `// Generated by scripts/pokemon-names.mjs from PokeAPI (${names.length} species). Don't edit by hand.
// The words of every Pokémon name, so the collection's "Did you mean" never "corrects" a real Pokémon (#266).
window.sleepyPokemonNames = new Set(${JSON.stringify([...words].sort())});
`;
await writeFile(OUT, file, "utf8");
console.log(`Wrote ${OUT}: ${names.length} species, ${words.size} words.`);
